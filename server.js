const http = require('http');
const fs = require('fs');
const path = require('path');

const PORT = process.env.PORT || 3000;

const MIME_TYPES = {
  '.html': 'text/html',
  '.css': 'text/css',
  '.js': 'text/javascript',
  '.json': 'application/json',
  '.png': 'image/png',
  '.jpg': 'image/jpeg',
  '.jpeg': 'image/jpeg',
  '.webp': 'image/webp',
  '.svg': 'image/svg+xml',
  '.ico': 'image/x-icon'
};

const server = http.createServer((req, res) => {
  let reqUrl = req.url.split('?')[0];
  if (reqUrl === '/') reqUrl = '/index.html';
  
  // Pretty URLs support
  if (reqUrl === '/shop') reqUrl = '/shop.html';
  if (reqUrl === '/about-us') reqUrl = '/about-us.html';
  if (reqUrl === '/contactus') reqUrl = '/contactus.html';
  if (reqUrl === '/privacy') reqUrl = '/privacy.html';
  if (reqUrl === '/cart') reqUrl = '/cart.html';
  if (reqUrl === '/wishlist') reqUrl = '/wishlist.html';

  const filePath = path.join(__dirname, reqUrl);
  const ext = path.extname(filePath).toLowerCase();
  const contentType = MIME_TYPES[ext] || 'application/octet-stream';

  fs.readFile(filePath, (err, content) => {
    if (err) {
      if (err.code === 'ENOENT') {
        res.writeHead(404, { 'Content-Type': 'text/html' });
        res.end('<h1>404 Not Found</h1><p><a href="/">Go to Home</a></p>');
      } else {
        res.writeHead(500);
        res.end(`Server Error: ${err.code}`);
      }
    } else {
      res.writeHead(200, { 'Content-Type': contentType });
      res.end(content);
    }
  });
});

server.listen(PORT, () => {
  console.log(`=======================================================`);
  console.log(` Zaiqa Craft Website is live!`);
  console.log(` URL: http://localhost:${PORT}`);
  console.log(` Press Ctrl+C to stop`);
  console.log(`=======================================================`);
});
